bool DynamicLinker::loadPlugins()
{
  // Load plugins
  std::vector<std::string> pluginsToLoad;

#if __cplusplus>=201703L
    std::vector<fs::path> paths;
    paths.push_back(fs::path(m_AppDataPath) / s_PluginFolder);
    paths.push_back(fs::current_path() / ".." / s_PluginFolder);
    paths.push_back(fs::path("..") / s_PluginFolder);
    paths.push_back(fs::path("../..") / s_PluginFolder);
    paths.push_back(fs::path("../../..") / s_PluginFolder);
    paths.push_back(fs::path("../../../..") / s_PluginFolder);
    std::string plugins_path{""};
    for(auto& p :paths) {
      if (fs::exists(p)) {
        plugins_path = p;
        break;
      }
    }
    if (plugins_path.empty()) {
      return false;   // Ignore plugins if there is no plugins folder at the executable location
    }

#ifdef WIN32
    //
    // Set additional PATH folder.
    // Windows XP SP1 or later, Windows Server 2003 or later
    //
    ::SetDllDirectoryA(plugins_path.string().c_str());
#endif

    for (auto& p : fs::directory_iterator(plugins_path)) {
      if (fs::is_regular_file(p.path())) {
        std::string f = p.path().string();
#ifdef WIN32
        // When building plugins in debug mode as part of the VS solution tree (required to debug the plugins),
        // files will be generated by VS in the plugins folder alongside the module file (.ilk file, .pdb file, and so on).
        // We ignore these files.
        if (!endsWith(f, ".dll") && !endsWith(f, ".DLL"))
          continue;
#else
        if (!endsWith(f, ".so")) {
          continue;
        }
#endif
        pluginsToLoad.push_back(f);
      }
    }
#else
  std::string plugins_path;
  std::vector<std::string> paths;
  paths.push_back(m_AppDataPath + "/" + s_PluginFolder);
  paths.push_back(std::string(LibSL::System::Application::executablePath()) + "../" + s_PluginFolder);
  paths.push_back("../" + s_PluginFolder);
  paths.push_back("../../" + s_PluginFolder);
  paths.push_back("../../../" + s_PluginFolder);
  paths.push_back("../../../../" + s_PluginFolder);
  bool ok = false;
  for(auto& p :paths) {
    plugins_path = p;
    if (LibSL::System::File::exists(plugins_path.c_str())) {
      ok = true;
      break;
    }
  }
  if (!ok) return false;

  // list available plugins
  plugins_path += "/";

  std::vector<std::string> files;
  LibSL::System::File::listFiles(plugins_path.c_str(), files);
  for(auto& f : files) {
    if (f == "." || f == "..") {
      continue;
    }
#ifdef WIN32
    if (!endsWith(f, ".dll") && !endsWith(f, ".DLL"))
      continue;
#else
    if (!endsWith(f, ".so")) {
      continue;
    }
#endif
    pluginsToLoad.push_back(plugins_path + f);
  }
#endif

  // TODO add mechanism to perform user checks on what plugins should be loaded
  // typically a list of checkbox
  for (const std::string &f : pluginsToLoad) {

#ifdef WIN32
    //TODO update to match UNIX implementation
    HMODULE hMod = ::LoadLibrary(f.c_str());
    if (hMod == NULL) {
      std::cerr << "[DynamicLinker::loadPlugins] could not load plugin '" << f << "' Error: " << ::GetLastError() << std::endl;
    }
    else {
      CREATEPLUGINFUNC createPlugin = (CREATEPLUGINFUNC)::GetProcAddress(hMod, "createPlugin");
      if (createPlugin == NULL) {
        std::cerr << "[DynamicLinker::loadPlugins] plugin '" << f << "' has no 'createPlugin' symbol exported, will be ignored!" << std::endl;
        ::FreeLibrary(hMod);
      }
      else {
        IPlugin* plugin = createPlugin();
        if (!plugin->initialize(*m_PluginEnvironment)) {
          std::cerr << "[DynamicLinker::loadPlugins] plugin '" << f << "' failed to initialize properly" << std::endl;
          ::FreeLibrary(hMod);
        }
        else {
          m_Plugins[f] = plugin;
        }

      }
    }
#else
    // SP and CZ 2019-09-30:
    // IMPORTANT
    // The flag RTLD_DEEPBIND avoid static variable name collision when loading shared libraries in UNIX.
#ifdef EMSCRIPTEN
    void * handle = dlopen(f.c_str(), RTLD_LAZY);
#else
    void * handle = dlopen(f.c_str(), RTLD_LAZY | RTLD_DEEPBIND);
#endif
    if (handle == nullptr) {
      std::cerr << "[DynamicLinker::loadPlugins] could not load plugin '" << f << "' Error: " << std::string(dlerror()) << std::endl;
    } else {
      CREATEPLUGINFUNC createPlugin = (CREATEPLUGINFUNC)dlsym(handle, "createPlugin");
      if (createPlugin == nullptr) {
        std::cerr << "[DynamicLinker::loadPlugins] plugin '" << f << "' has no 'createPlugin' symbol exported, will be ignored" << std::endl;
        dlclose(handle);
      } else {
        IPlugin* plugin = createPlugin();
        if (plugin->initialize(*m_PluginEnvironment)) {
          m_Plugins[f] = plugin;
        } else {
          std::cerr << "[DynamicLinker::loadModules] plugin '" << f << "' failed to initialize properly" << std::endl;
          dlclose(handle);
        }
      }
    }
#endif
  }
  return true;
}

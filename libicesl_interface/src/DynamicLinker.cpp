const std::string DynamicLinker::s_PluginFolder = "icesl-plugins";

// ----------------------------------------------------------------------------

static bool endsWith(const std::string& str, const std::string& suffix)
{
  return str.size() >= suffix.size() && 0 == str.compare(str.size()-suffix.size(), suffix.size(), suffix);
}

// ----------------------------------------------------------------------------

DynamicLinker::DynamicLinker(const std::string& appDataPath,
                             std::unique_ptr<IPluginEnvironment> pluginEnvironment)
  : m_AppDataPath(appDataPath),
    m_PluginEnvironment(std::move(pluginEnvironment))
{}

// ----------------------------------------------------------------------------

DynamicLinker::~DynamicLinker()
{
  // Close plugins
  for (auto it : m_Plugins) {
    it.second->dispose();
  }
  // TODO call dlclose (or equivalent on windows ?
  // for this purpose we need to save handle in vector when loading lib
}

